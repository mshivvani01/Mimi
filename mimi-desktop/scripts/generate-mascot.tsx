/**
 * Renders every Mimi pose from src/components/MimiArt.tsx to a transparent PNG and rewrites the manifest.
 * Run with: npm run assets:mascot
 */
import { createHash } from 'node:crypto';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { renderToStaticMarkup } from 'react-dom/server';
import { Resvg } from '@resvg/resvg-js';
import { MimiArt } from '../src/components/MimiArt';
import { POSES } from '../src/mascot/poses';

const WIDTH = 720; // 300x320 viewBox -> 720x768
const outDir = path.resolve(__dirname, '../src/assets/mascot');
mkdirSync(outDir, { recursive: true });

const poses: Record<string, unknown> = {};
for (const pose of POSES) {
  const svg = renderToStaticMarkup(<MimiArt pose={pose} />);
  const png = new Resvg(svg, { fitTo: { mode: 'width', value: WIDTH } }).render();
  const file = `mimi-${pose}.png`;
  writeFileSync(path.join(outDir, file), png.asPng());
  const bytes = readFileSync(path.join(outDir, file));
  poses[pose] = { file, png: true, width: png.width, height: png.height, alpha: true, bytes: bytes.length, sha256: createHash('sha256').update(bytes).digest('hex').slice(0, 16), source: 'rendered from src/components/MimiArt.tsx via scripts/generate-mascot.tsx' };
  console.log('wrote', file, png.width + 'x' + png.height, bytes.length + ' bytes');
}

const manifest = {
  version: 2,
  note: 'Generated by scripts/generate-mascot.tsx. Artwork is original, hand-built layered vector art rendered to transparent PNG (NOT output of an AI image model). Every entry below corresponds to a file that exists.',
  poses,
};
writeFileSync(path.resolve(__dirname, '../src/assets/mascot-manifest.json'), JSON.stringify(manifest, null, 2) + '\n');
